//! Course content: Thai for Korean speakers.
//! Every Thai word has a Hangul pronunciation guide, its tones and a Korean meaning.
//!
//! Tones are written one letter per Thai syllable:
//! M = 평성 (mid), L = 저성 (low), F = 하강 (falling), H = 고성 (high), R = 상승 (rising).

pub struct Word {
    pub th: &'static str,
    pub pron: &'static str,
    pub ko: &'static str,
    pub tone: &'static str,
}

pub struct Sentence {
    /// Thai words in order (these become the word tiles). Written in the male form;
    /// the app switches ครับ/ผม to ค่ะ/ฉัน for learners who choose the female form.
    pub th: &'static [&'static str],
    /// Korean meaning split into tiles.
    pub ko: &'static [&'static str],
    /// Other natural Korean word orders that are also correct.
    pub alts: &'static [&'static [&'static str]],
}

impl Sentence {
    pub fn korean(&self) -> String {
        self.ko.join(" ")
    }
}

pub struct Unit {
    pub title: &'static str,
    pub desc: &'static str,
    pub color: [u8; 3],
    pub words: &'static [Word],
    pub sentences: &'static [Sentence],
}

const fn w(th: &'static str, pron: &'static str, ko: &'static str, tone: &'static str) -> Word {
    Word { th, pron, ko, tone }
}

const fn s(th: &'static [&'static str], ko: &'static [&'static str]) -> Sentence {
    Sentence { th, ko, alts: &[] }
}

const fn sa(th: &'static [&'static str], ko: &'static [&'static str], alts: &'static [&'static [&'static str]]) -> Sentence {
    Sentence { th, ko, alts }
}

pub const LESSONS_PER_UNIT: usize = 5; // 4 lessons + 1 unit review

/// Course levels: (first unit index, name, what it covers).
pub static LEVELS: &[(usize, &str, &str)] = &[
    (0, "기초", "인사와 꼭 필요한 말"),
    (6, "초급", "생활 속 표현"),
    (12, "중급", "시제, 이유, 비교, 의견 말하기"),
];

pub fn level_name(unit: usize) -> &'static str {
    LEVELS.iter().rev().find(|(start, _, _)| unit >= *start).map(|l| l.1).unwrap_or("기초")
}

pub fn level_start(unit: usize) -> Option<(&'static str, &'static str)> {
    LEVELS.iter().find(|(start, _, _)| *start == unit).map(|l| (l.1, l.2))
}

