/// The five Thai tones, explained for Korean speakers.
pub struct Tone {
    pub code: char,
    pub mark: &'static str,
    pub name: &'static str,
    pub how: &'static str,
    pub example: &'static str,
    pub example_pron: &'static str,
    pub example_ko: &'static str,
}

pub static TONES: &[Tone] = &[
    Tone { code: 'M', mark: "→", name: "평성", how: "보통 높이로 평평하게", example: "ไมล์", example_pron: "마이", example_ko: "마일 (거리)" },
    Tone { code: 'L', mark: "↓", name: "저성", how: "낮은 소리로 평평하게", example: "ใหม่", example_pron: "마이", example_ko: "새로운" },
    Tone { code: 'F', mark: "↘", name: "하강", how: "높게 시작해 뚝 떨어지게", example: "ไม่", example_pron: "마이", example_ko: "아니다, 안" },
    Tone { code: 'H', mark: "↑", name: "고성", how: "높은 소리로 살짝 올리며", example: "ไม้", example_pron: "마이", example_ko: "나무" },
    Tone { code: 'R', mark: "↗", name: "상승", how: "낮게 내려갔다가 끝을 올리며", example: "ไหม", example_pron: "마이", example_ko: "~나요? (질문)" },
];

pub fn tone_of(code: char) -> Option<&'static Tone> {
    TONES.iter().find(|t| t.code == code)
}

/// Tone arrows for a tone string, e.g. "LLM" -> "↓↓→".
pub fn tone_marks(tone: &str) -> String {
    tone.chars().filter_map(|c| tone_of(c).map(|t| t.mark)).collect()
}

